export const messages: Record<Language, Record<MessageKey, string>> = { zh, en };

export function t(lang: Language, key: MessageKey): string {
  return messages[lang][key] ?? messages.zh[key] ?? key;
}

/** 替换模板中的 {name} 占位符。 */
export function fill(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    vars[name] !== undefined ? vars[name] : whole
  );
}
